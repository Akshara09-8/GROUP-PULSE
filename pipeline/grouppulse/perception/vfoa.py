"""Learned visual focus of attention (VFOA): face cues -> gaze target, per camera.

This is the classic AMI approach: each close-up camera films one fixed seat, so for that camera
each target (another seat, the screen, the whiteboard, the table) shows up as a typical head
pose. We fit one Gaussian (full covariance) per (camera, target) from AMI's focus-of-attention
labels and pick the most likely target.

Features: PnP head yaw/pitch plus direct cues from the 5 face points and the face box
(io.TrackRow.nose_dx ... face_w). The direct cues matter because PnP from 5 points barely moves
in pitch (so "looking at the table" is invisible to it) and flips sign on big turns.

Because seats and cameras are fixed per room, a model fitted on labelled meetings transfers to
other meetings recorded in the same room.
"""

from __future__ import annotations

import math  # noqa: F401  (used by TargetModel and viterbi)
import tomllib
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable

import numpy as np

from ..data.config import REPO_ROOT
from .geometry import angle_diff, direction_to, wrap180
from .layout import SeatLayout

FEATURES = ("head_yaw", "head_pitch", "nose_dx", "nose_dy", "face_cx", "face_cy", "face_w")
FEATURE_SETS = {
    "angles": ("head_yaw", "head_pitch"),
    "eyes": ("head_yaw", "head_pitch", "eye_h", "eye_v"),          # MediaPipe eye direction
    "cues": FEATURES,                                               # YuNet geometric cues
    "eyes+torso": ("head_yaw", "head_pitch", "eye_h", "eye_v", "torso_yaw"),
}
MIN_COUNT = 15        # samples needed to model a target
RIDGE = 0.05          # covariance regulariser, as a share of each feature's overall variance


@dataclass(frozen=True)
class Sample:
    view: str
    yaw: float
    pitch: float
    target: str
    extra: tuple[float, ...] = ()   # FEATURES[2:] when available

    @property
    def x(self) -> tuple[float, ...]:
        return (self.yaw, self.pitch) + tuple(self.extra)


@dataclass
class TargetModel:
    mean: list[float]
    cov: list[list[float]]
    prior: float

    def __post_init__(self):
        self._cache: dict[int, tuple[np.ndarray, np.ndarray, float]] = {}

    def loglik(self, x: tuple[float, ...]) -> float:
        d = len(x)
        if d not in self._cache:
            c = np.asarray(self.cov)[:d, :d]
            sign, logdet = np.linalg.slogdet(c)
            self._cache[d] = (np.asarray(self.mean[:d]), np.linalg.inv(c), logdet)
        mu, inv, logdet = self._cache[d]
        z = np.asarray(x) - mu
        return float(-0.5 * (z @ inv @ z) - 0.5 * logdet + math.log(self.prior))


@dataclass
class VfoaModel:
    site: str
    cameras: dict[str, dict[str, TargetModel]] = field(default_factory=dict)
    features: tuple[str, ...] = FEATURES[:2]
    # yaw/pitch-only model fitted on ALL rows, used when a row lacks the extra features
    # (e.g. MediaPipe could not read a profile face, so there is no eye direction)
    fallback: dict[str, dict[str, TargetModel]] = field(default_factory=dict)
    # per-camera confusion C[true, predicted] measured on held-out training meetings (quantify.py);
    # used to correct attention shares, never per-frame labels
    confusion: dict = field(default_factory=dict)

    def scores(self, view: str, yaw: float | None, pitch: float | None,
               extra: tuple[float, ...] = ()) -> dict[str, float]:
        """Log-likelihood (+ log prior) of each target; empty when nothing can be said."""
        if yaw is None or pitch is None:
            return {}
        full = len(extra) == len(self.features) - 2
        if full and view in self.cameras:
            models, x = self.cameras[view], (yaw, pitch) + tuple(extra)
        elif view in self.fallback:
            models, x = self.fallback[view], (yaw, pitch)
        elif view in self.cameras:
            models, x = self.cameras[view], (yaw, pitch)   # marginal of the full model
        else:
            return {}
        return {k: m.loglik(x) for k, m in models.items()}

    def predict(self, view: str, yaw: float | None, pitch: float | None,
                extra: tuple[float, ...] = ()) -> str:
        s = self.scores(view, yaw, pitch, extra)
        return max(s, key=s.get) if s else "unknown"

    def predict_row(self, view: str, row) -> str:
        extra = tuple(getattr(row, f) for f in self.features[2:])
        if any(v is None for v in extra):
            extra = ()
        return self.predict(view, row.head_yaw, row.head_pitch, extra)

    # --- persistence (plain TOML so it can be read and diffed) ---
    def save(self, path: str | Path) -> Path:
        p = Path(path)
        fmt = lambda xs: "[" + ", ".join(f"{v:.6g}" for v in xs) + "]"  # noqa: E731
        lines = [f"# Learned VFOA model for the {self.site} room. Generated by grouppulse.perception.calibrate.",
                 f'site = "{self.site}"', "features = [" + ", ".join(f'"{f}"' for f in self.features) + "]", ""]
        for table, cams in (("cameras", self.cameras), ("fallback", self.fallback)):
            for view, models in sorted(cams.items()):
                for tgt, m in sorted(models.items()):
                    lines += [f'[{table}.{view}."{tgt}"]', f"prior = {m.prior:.5f}", f"mean = {fmt(m.mean)}",
                              "cov = [" + ", ".join(fmt(r) for r in m.cov) + "]", ""]
        if self.confusion:
            from .quantify import TARGETS
            lines += ["# Rows = true target, columns = predicted, in this order:",
                      "[confusion]", "targets = [" + ", ".join(f'"{t}"' for t in TARGETS) + "]", "", "[confusion.matrices]"]
            for view, c in sorted(self.confusion.items()):
                lines.append(f"{view} = [" + ", ".join(fmt(r) for r in np.asarray(c)) + "]")
            lines.append("")
        p.write_text("\n".join(lines), encoding="utf-8")
        return p

    @classmethod
    def load(cls, path: str | Path) -> "VfoaModel":
        with Path(path).open("rb") as f:
            raw = tomllib.load(f)
        read = lambda t: {v: {k: TargetModel(m["mean"], m["cov"], m["prior"]) for k, m in tg.items()}  # noqa: E731
                          for v, tg in raw.get(t, {}).items()}
        from .quantify import from_jsonable
        return cls(raw["site"], read("cameras"), tuple(raw.get("features", FEATURES[:2])), read("fallback"),
                   from_jsonable(raw.get("confusion")))


def default_path(site: str) -> Path:
    return REPO_ROOT / "configs" / f"vfoa_{site}.toml"


def _fit_cams(samples: list[Sample], dims: int, min_count: int) -> dict[str, dict[str, TargetModel]]:
    by: dict[str, dict[str, list[Sample]]] = defaultdict(lambda: defaultdict(list))
    for s in samples:
        by[s.view][s.target].append(s)
    out: dict[str, dict[str, TargetModel]] = {}
    for view, targets in by.items():
        kept = {t: ss for t, ss in targets.items() if len(ss) >= min_count}
        if not kept:
            continue
        allx = np.array([s.x[:dims] for ss in kept.values() for s in ss])
        ridge = np.diag(np.maximum(allx.var(axis=0), 1e-6) * RIDGE)
        n = len(allx)
        out[view] = {}
        for t, ss in kept.items():
            x = np.array([s.x[:dims] for s in ss])
            cov = np.cov(x, rowvar=False) + ridge
            out[view][t] = TargetModel(x.mean(axis=0).tolist(), cov.tolist(), len(ss) / n)
    return out


def fit(samples: Iterable[Sample], site: str, min_count: int = MIN_COUNT,
        features: tuple[str, ...] | None = None) -> VfoaModel:
    """Fit per-camera target Gaussians.

    `features` defaults to the widest set every sample has. With more than yaw/pitch, the main
    model uses only samples that have every feature, and a yaw/pitch fallback is fitted on all."""
    samples = [s for s in samples if s.target != "unknown"]
    if features is None:
        features = FEATURES[: min((len(s.x) for s in samples), default=2)]
    dims = len(features)
    complete = [s for s in samples if len(s.x) >= dims]
    model = VfoaModel(site, _fit_cams(complete, dims, min_count), tuple(features))
    if dims > 2:
        model.fallback = _fit_cams(samples, 2, min_count)
    return model


def smooth(labels: list[str], window: int = 5) -> list[str]:
    """Majority filter over a centred window (5 samples = 1 s at 5 fps); ties keep the original."""
    if window <= 1:
        return list(labels)
    h = window // 2
    out = []
    for i, lab in enumerate(labels):
        c = Counter(labels[max(0, i - h): i + h + 1]).most_common()
        out.append(c[0][0] if c[0][1] > (c[1][1] if len(c) > 1 else 0) else lab)
    return out


def viterbi(frame_scores: list[dict[str, float]], stay: float = 0.9) -> list[str]:
    """Most likely target sequence under a 'sticky' HMM: attention stays put with probability `stay`
    per step and otherwise jumps to any other target equally. Frames with no scores (no face) are
    bridged: the path carries through them and they come out labelled 'unknown'."""
    states = sorted({k for s in frame_scores for k in s})
    if not states:
        return ["unknown"] * len(frame_scores)
    n = len(states)
    ls, lm = math.log(stay), math.log((1 - stay) / max(1, n - 1))
    prev = {k: 0.0 for k in states}
    back: list[dict[str, str]] = []
    for s in frame_scores:
        ranked = sorted(prev, key=prev.get, reverse=True)
        cur, ptr = {}, {}
        for k in states:
            other = ranked[0] if ranked[0] != k else (ranked[1] if n > 1 else k)
            via_stay, via_move = prev[k] + ls, prev[other] + lm
            ptr[k] = k if via_stay >= via_move else other
            cur[k] = max(via_stay, via_move) + s.get(k, -1e3 if s else 0.0)
        back.append(ptr)
        prev = cur
    k = max(prev, key=prev.get)
    path = [k]
    for ptr in reversed(back[1:]):
        k = ptr[k]
        path.append(k)
    path.reverse()
    return [p if s else "unknown" for p, s in zip(path, frame_scores)]


def fit_camera_dirs(samples: Iterable[Sample], layout: SeatLayout) -> dict[str, float]:
    """Geometric calibration: the camera direction that best explains labelled glances.

    camera_dir = direction(viewer seat -> target) - 180 - yaw, circular median per camera."""
    viewer_of = {v: p for p, v in layout.camera_of.items()}
    est: dict[str, list[float]] = defaultdict(list)
    for s in samples:
        viewer = viewer_of.get(s.view)
        pos = layout.seats.get(s.target) or layout.objects.get(s.target)
        if viewer is None or pos is None or s.target == viewer:
            continue
        est[s.view].append(wrap180(direction_to(layout.seats[viewer], pos) - 180.0 - s.yaw))
    return {view: round(min(xs, key=lambda c: sum(angle_diff(c, x) for x in xs)), 1)
            for view, xs in est.items()}
